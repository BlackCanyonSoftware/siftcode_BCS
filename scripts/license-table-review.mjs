// Writes docs/license-table-review.md: the license compatibility table in a form a person can review,
// generated from the code in dist/ so the sheet cannot drift from what the rules do.
// Run `npm run build` first, then `npm run review:license-table`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL, URL } from 'node:url';

const dist = fileURLToPath(new URL('../dist/rules/licenses/', import.meta.url));
const load = (file) => import(pathToFileURL(`${dist}${file}`).href);
const { assessDependency, COMPATIBILITY_TABLE_VERSION, traitsOf } = await load('compatibility.js');
const { loadCatalog } = await load('catalog.js');
const { parseExpression } = await load('spdx.js');

const catalog = await loadCatalog();
const expression = (text) => {
  const parsed = parseExpression(text, catalog);
  if (!parsed.ok) throw new Error(`${text}: ${parsed.reason}`);
  return parsed.expression;
};

const PROJECTS = [
  'MIT',
  'Apache-2.0',
  'BSD-3-Clause',
  'MPL-2.0',
  'LGPL-3.0-only',
  'GPL-2.0-only',
  'GPL-2.0-or-later',
  'GPL-3.0-only',
  'AGPL-3.0-only',
  'LicenseRef-Proprietary',
];
const DEPENDENCIES = [
  'MIT',
  'Apache-2.0',
  'BSD-4-Clause',
  'MPL-2.0',
  'EPL-1.0',
  'EPL-2.0',
  'CDDL-1.0',
  'LGPL-2.1-only',
  'LGPL-3.0-only',
  'GPL-2.0-only',
  'GPL-2.0-or-later',
  'GPL-3.0-only',
  'AGPL-3.0-only',
  'EUPL-1.2',
  'SSPL-1.0',
  'CC-BY-NC-4.0',
];

const SYMBOL = {
  copyleft: 'C',
  'network-copyleft': 'N',
  incompatible: 'X',
  restricted: 'R',
  obligation: 'o',
};
const reasons = new Map();

function cell(project, dependency) {
  const assessment = assessDependency(expression(project), expression(dependency));
  if (!assessment) return '.';
  const letter = SYMBOL[assessment.kind];
  reasons.set(`${assessment.kind}/${assessment.severity}|${assessment.reason}`, assessment);
  return assessment.severity === 'warning' ? letter : `(${letter})`;
}

const FAMILIES = [
  'permissive',
  'public-domain',
  'weak-copyleft',
  'strong-copyleft',
  'network-copyleft',
  'restricted',
];
const byFamily = new Map(FAMILIES.map((family) => [family, []]));
for (const { id } of catalog.entries.values()) {
  const traits = traitsOf(id);
  if (traits && byFamily.has(traits.family)) byFamily.get(traits.family).push(id);
}

const lines = [
  '# License compatibility table: review sheet',
  '',
  `Table version **${COMPATIBILITY_TABLE_VERSION}**. Generated by \`npm run review:license-table\` from the code in \`src/rules/licenses/compatibility.ts\`; do not edit by hand.`,
  '',
  "SiftCode compares each dependency's license with the project's license using this table, to point out likely problems. It does not know whether a dependency is linked, bundled, or only run as a separate program, so its wording is conditional. If a row looks wrong, fix it in the code and regenerate this sheet. Sources are listed under each reason.",
  '',
  '## 1. How licenses are sorted',
  '',
  ...FAMILIES.flatMap((family) => [
    `- **${family}** (${byFamily.get(family).length}): ${byFamily.get(family).join(', ')}`,
  ]),
  '',
  'A license on the SPDX list but missing here is reported as "outside the table" (info), not judged. A GNU license with a linking exception (for example `GPL-2.0-only WITH Classpath-exception-2.0`) counts as weak copyleft. Non-commercial and no-derivatives Creative Commons licenses count as restricted.',
  '',
  '## 2. What is reported: project license (rows) against dependency license (columns)',
  '',
  'Key: `.` nothing reported; `C` strong copyleft; `N` network copyleft (AGPL); `X` incompatible; `R` restricted use; `o` weak-copyleft obligation. A letter alone is a **warning**; a letter in parentheses is **info**. `LicenseRef-Proprietary` is a project that reserves all rights.',
  '',
  `| project \\ dependency | ${DEPENDENCIES.join(' | ')} |`,
  `| --- | ${DEPENDENCIES.map(() => ':-:').join(' | ')} |`,
  ...PROJECTS.map(
    (project) => `| ${project} | ${DEPENDENCIES.map((d) => cell(project, d)).join(' | ')} |`,
  ),
  '',
  '## 3. The reasons, with their sources',
  '',
  ...[...reasons.values()]
    .sort((a, b) => (a.reason < b.reason ? -1 : 1))
    .flatMap((assessment) => [
      `- **${assessment.kind}, ${assessment.severity}.** ${assessment.reason}.`,
      ...assessment.sources.map((source) => `  - ${source.standard}: ${source.url ?? ''}`),
    ]),
  '',
  '## 4. Rules that are not in the matrix',
  '',
  '- A dependency under `A OR B` is judged by the easier side; `A AND B` by the stricter. A dual-licensed project (`MIT OR GPL-3.0-only`) is judged by the alternative that fits best.',
  '- A restricted dependency (SSPL, BUSL, Elastic, CC-BY-NC) is reported whatever the project license is, even when the project has none.',
  '- Without a project license, only restricted dependencies are reported.',
  '- A project that declares itself `UNLICENSED` or `Proprietary`, or whose LICENSE file reserves all rights, is treated as `LicenseRef-Proprietary`.',
  "- A dependency's license is read from what is installed or in the lockfile. If it cannot be found it is reported as unknown, never assumed.",
  '',
];
writeFileSync(
  fileURLToPath(new URL('../docs/license-table-review.md', import.meta.url)),
  `${lines.join('\n')}\n`,
);
console.log(`Wrote docs/license-table-review.md (${reasons.size} distinct reasons).`);
