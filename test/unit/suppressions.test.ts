import { describe, expect, it } from 'vitest';
import { scan } from '../../src/core/scan.js';
import { onlyRule, useProjects } from '../helpers/project.js';

const projects = useProjects();
const config = onlyRule('SC-MET-001', { maxLines: 3 });

/** A 5-line JavaScript function: longer than the limit of 3 lines. */
const longFunction = (name: string, firstLine = '') =>
  `function ${name}() {${firstLine}\n  a();\n  b();\n  c();\n}\n`;

async function scanFiles(files: Record<string, string>) {
  return scan(await projects.create(files), { config });
}

describe('inline suppressions (US-070)', () => {
  it('accepts a finding when a comment on the same line names the rule and gives a reason', async () => {
    const result = await scanFiles({
      'a.js': longFunction('work', ' // siftcode-ignore SC-MET-001: legacy parser, see #42'),
    });

    expect(result.findings).toEqual([]);
    expect(result.accepted).toHaveLength(1);
    expect(result.accepted[0]).toMatchObject({
      finding: { ruleId: 'SC-MET-001', path: 'a.js', startLine: 1 },
      via: { kind: 'suppression', reason: 'legacy parser, see #42', line: 1 },
    });
    expect(result.notes).toEqual([]);
  });

  it.each([
    [
      'a.js',
      '// siftcode-ignore SC-MET-001: reason\nfunction work() {\n  a();\n  b();\n  c();\n}\n',
    ],
    [
      'a.ts',
      '/* siftcode-ignore SC-MET-001: reason */\nfunction work() {\n  a();\n  b();\n  c();\n}\n',
    ],
    [
      'a.py',
      '# siftcode-ignore SC-MET-001: reason\ndef work():\n    a()\n    b()\n    c()\n    d()\n',
    ],
    [
      'A.cs',
      'class A\n{\n    // siftcode-ignore SC-MET-001: reason\n    void Work()\n    {\n        a();\n        b();\n        c();\n    }\n}\n',
    ],
  ])('accepts a finding on the line after a comment on its own line in %s', async (file, code) => {
    const result = await scanFiles({ [file]: code });

    expect(result.findings).toEqual([]);
    expect(result.accepted).toHaveLength(1);
    expect(result.notes).toEqual([]);
  });

  it('skips blank lines and stacked comments between the comment and the code', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-002: other rule\n\n// siftcode-ignore SC-MET-001: reason\n${longFunction('work')}`,
    });

    expect(result.findings).toEqual([]);
    expect(result.accepted).toHaveLength(1);
  });

  it('does not reach past code: a comment two statements above does nothing', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-001: reason\nconst x = 1;\n${longFunction('work')}`,
    });

    expect(result.findings).toHaveLength(1);
    expect(result.accepted).toEqual([]);
    expect(result.notes).toEqual(['a.js:1: siftcode-ignore SC-MET-001 matched no finding.']);
  });

  it('accepts a rule for the whole file with siftcode-ignore-file', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore-file SC-MET-001: generated by a tool\n${longFunction('one')}${longFunction('two')}`,
    });

    expect(result.findings).toEqual([]);
    expect(result.accepted.map((a) => a.finding.startLine)).toEqual([2, 7]);
    expect(result.accepted[0]?.via).toMatchObject({
      kind: 'suppression',
      reason: 'generated by a tool',
    });
  });

  it('takes several rule ids in one comment', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-002, SC-MET-001: both are expected here\n${longFunction('work')}`,
    });

    expect(result.findings).toEqual([]);
    expect(result.accepted).toHaveLength(1);
    expect(result.notes).toEqual([]);
  });

  it('does not suppress, and says why, when the reason is missing', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-001\n${longFunction('work')}`,
      'b.js': `// siftcode-ignore SC-MET-001:   \n${longFunction('work')}`,
    });

    expect(result.findings).toHaveLength(2);
    expect(result.accepted).toEqual([]);
    expect(result.notes).toEqual([
      'a.js:1: siftcode-ignore needs a reason after the rule id, for example "siftcode-ignore SC-MET-001: legacy code, see #42". The finding stays.',
      'b.js:1: siftcode-ignore needs a reason after the rule id, for example "siftcode-ignore SC-MET-001: legacy code, see #42". The finding stays.',
    ]);
  });

  it('does not suppress, and says why, for an unknown rule id or no rule id', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-999: reason\n${longFunction('work')}`,
      'b.js': `// siftcode-ignore: reason\n${longFunction('work')}`,
    });

    expect(result.findings).toHaveLength(2);
    expect(result.notes).toEqual([
      'a.js:1: siftcode-ignore names SC-MET-999, which is not a SiftCode rule.',
      'b.js:1: siftcode-ignore needs a rule id before the reason, for example "siftcode-ignore SC-MET-001: reason".',
    ]);
  });

  it('does not treat the text inside a string as a comment', async () => {
    const result = await scanFiles({
      'a.js': `const hint = "// siftcode-ignore SC-MET-001: not a comment";\n${longFunction('work')}`,
    });

    expect(result.findings).toHaveLength(1);
    expect(result.accepted).toEqual([]);
    expect(result.notes).toEqual([]);
  });

  it('ignores a comment that only mentions the directive, as documentation does', async () => {
    const result = await scanFiles({
      'a.js': [
        '// to hide a finding, write siftcode-ignore SC-MET-001: reason',
        '/**',
        ' * Example:',
        ' *     // siftcode-ignore SC-MET-001: legacy parser',
        ' */',
        longFunction('work'),
      ].join('\n'),
    });

    expect(result.findings).toHaveLength(1);
    expect(result.accepted).toEqual([]);
    expect(result.notes).toEqual([]);
  });

  it('does not report a comment for a rule that is switched off as unused', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-002: reason\nconst x = 1;\n`,
    });

    expect(result.notes).toEqual([]);
  });

  it('keeps the finding when the comment names a different rule', async () => {
    const result = await scanFiles({
      'a.js': `// siftcode-ignore SC-MET-002: reason\n${longFunction('work')}`,
    });

    expect(result.findings).toHaveLength(1);
    expect(result.accepted).toEqual([]);
  });
});
